// section печатает шапку сценария: заголовок и пару строк о том, какая
// проблема решается, — чтобы вывод программы читался без исходников.
func section(title, about string) {
	fmt.Printf("\n%s\n=== %s ===\n%s\n", strings.Repeat("─", 74), title, about)
}

// ms форматирует длительность как «123мс» — в выводе сценариев важны порядки
// величин, а не наносекунды. Для совсем коротких интервалов (чтение файлов с
// диска укладывается в доли миллисекунды) остаётся один знак после запятой,
// иначе результат выглядел бы как мгновенный.
func ms(d time.Duration) string {
	if d < time.Millisecond {
		return fmt.Sprintf("%.1fмс", float64(d.Microseconds())/1000)
	}
	return fmt.Sprintf("%dмс", d.Milliseconds())
}

// since — то же самое для «сколько прошло с момента start».
func since(start time.Time) string {
	return ms(time.Since(start))
}
