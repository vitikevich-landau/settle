// Демонстрационная программа: settle в задачах, похожих на боевые.
//
// Запуск из корня репозитория:
//
//	go run ./examples/realworld
//
// Чем это отличается от ./examples: там сценарии синтетические — задачи просто
// спят и возвращают строку, чтобы был виден сам механизм. Здесь каждый
// сценарий — уменьшенная копия реальной работы: настоящие HTTP-запросы,
// настоящее чтение файлов с диска, настоящие дедлайны и отмена, которая
// доезжает до другого конца соединения.
//
// Внешняя сеть не нужна: все «микросервисы» поднимаются локально через
// httptest, файлы создаются во временной директории. Программа одинаково
// работает офлайн и в CI.
//
// Сценарии и приёмы, которые они показывают:
//
//	bff.go       Stream: своя политика обязательных и необязательных
//	             фрагментов, обработка результатов по мере готовности
//	failover.go  Any: первый успех среди реплик и отложенный старт дублей
//	             (hedged requests)
//	health.go    AllSettled: /readyz с полным отчётом и общим дедлайном
//	checksums.go AllSettled: хэши файлов, конкурентность пачками и
//	             отменяемый ввод-вывод, изначально не знающий про ctx
//	signup.go    All: первый отказ отменяет остальные проверки и экономит
//	             платный внешний вызов
