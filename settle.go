// Пакет settle запускает набор функций конкурентно и собирает их результаты
// в духе Promise-комбинаторов из JavaScript, но с отменой через context.
//
// [AllSettled], [All], [Race] и [Any] покрывают типовые сценарии. [Stream] —
// низкоуровневый нативный итератор Go (range-over-func, Go 1.23+) для случаев,
// когда результат нужно обработать сразу по мере готовности, сохранить индекс
// задачи или применить собственное правило остановки. Все комбинаторы
// реализованы поверх Stream и разделяют с ним один контракт отмены и уборки.
package settle

import (
	"context"
	"errors"
	"fmt"
	"iter"
	"runtime/debug"
	"sync"
)

// Result — итог выполнения одной задачи. Если Err == nil, задача завершилась
// успешно и результат лежит в Value.
//
// Если Err != nil, в Value лежит ровно то, что вернула сама задача: Stream
// передаёт её возврат как есть и ничего не занулит за вас. Осмысленность Value
// при ошибке определяет контракт задачи. Многие задачи возвращают нулевое
// значение, другие — частичный результат, как io.Reader; оба варианта
// нормальны и без изменений доезжают до потребителя.
//
// Исключение — паника и runtime.Goexit: там возврата задачи не существует,
// поэтому Result конструирует сам Stream и Value в нём всегда нулевой.
type Result[T any] struct {
	Value T
	Err   error
}

// ErrGoexit приходит в Result.Err, когда задача завершила свою горутину
// через runtime.Goexit — чаще всего это t.Fatal / t.FailNow (или require.*
// из testify), вызванные прямо внутри задачи в чьём-нибудь тесте. Goexit —
// не паника: recover его не видит, и задача не возвращает ни значения, ни
// ошибки. Но контракт «ровно один Result на задачу» обязан выполняться —
// иначе потребитель завис бы навсегда, ожидая недостающий результат.
var ErrGoexit = errors.New("settle: task exited via runtime.Goexit")

// PanicError сообщает о панике, перехваченной внутри задачи. Вместо того
// чтобы уронить весь процесс, паника доставляется потребителю через
// Result.Err — остальные задачи продолжают работать как ни в чём не бывало.
type PanicError struct {
	Value any    // значение, переданное в panic
	Stack []byte // стек горутины, снятый в момент перехвата паники
}

func (p *PanicError) Error() string {
	return fmt.Sprintf("settle: task panicked: %v", p.Value)
}

// Unwrap отдаёт значение паники, если оно само является ошибкой: тогда
// цепочки errors.Is / errors.As проходят сквозь PanicError до исходной
// ошибки — идиома panic(err) внутри задачи остаётся различимой для
// сентинелей. Если в panic передали не ошибку (строку, число и т.п.),
// Unwrap возвращает nil и цепочка обрывается.
func (p *PanicError) Unwrap() error {
	if err, ok := p.Value.(error); ok {
		return err
	}
	return nil
}

// Stream возвращает итератор по парам (индекс, Result). При обходе (range)
// итератор запускает по одной горутине на каждую fn и отдаёт результаты в
// порядке завершения задач.
//
// Контракт:
//
//   - Запуск ленивый: задачи стартуют не при вызове Stream, а в момент
//     обхода итератора. Каждый новый обход возвращённой последовательности
//     запускает все fn заново — результаты не мемоизируются.
//   - Порядок завершения не гарантирован. Какая задача дала какой результат,
//     определяет индекс — позиция fn в списке аргументов.
//   - Выход из range-цикла через break отменяет контекст, переданный ещё не
//     завершившимся задачам, и дожидается их возврата. Результаты, «созревшие»
//     после break, молча отбрасываются — включая ошибки и паники.
//   - Ровно один Result на задачу. Паника внутри fn перехватывается и
//     приходит как *[PanicError] в Result.Err; задача, завершившая горутину
//     через runtime.Goexit (например, t.Fatal внутри теста), даёт Result с
//     ошибкой [ErrGoexit]. Остальные задачи в обоих случаях не затрагиваются.
//   - К моменту выхода из range-цикла — обычного или через break — ни одна
//     горутина, запущенная итератором, уже не работает. Чтобы это завершение
//     было быстрым, задачи обязаны реагировать на отмену ctx.
func Stream[T any](ctx context.Context, fns ...func(context.Context) (T, error)) iter.Seq2[int, Result[T]] {
	return func(yield func(int, Result[T]) bool) {
		// Нет задач — нет результатов: итератор просто не даёт ни одной пары.
		if len(fns) == 0 {
			return
		}

		// Дочерний контекст: его отмена — наш рычаг, которым мы просим
		// оставшиеся задачи свернуться, когда потребитель ушёл раньше времени.
		ctx, cancel := context.WithCancel(ctx)

		// Пара «индекс + результат», которую воркер кладёт в канал: индекс
		// нужен потребителю, чтобы понять, чья это работа.
		type item struct {
			idx int
			res Result[T]
		}
		// Буфер = len(fns): каждый воркер всегда может положить свой
		// результат и выйти, даже если потребитель давно ушёл. Никто не
		// блокируется на отправке, никто не утекает.
		out := make(chan item, len(fns))

		var wg sync.WaitGroup
		// Отложенная уборка — это и есть гарантия структурной конкурентности.
		// Порядок LIFO важен: сначала выполняется cancel (разбудить всех),
		// затем wg.Wait (проводить каждого до двери).
		defer wg.Wait()
		defer cancel()

		// Запускаем всех воркеров. Начиная с Go 1.22 переменные цикла i и fn
		// создаются заново на каждой итерации, поэтому захватывать их в
		// замыкании безопасно.
		for i, fn := range fns {
			wg.Add(1)
			go func() {
				defer wg.Done()
				// Пессимистичная заготовка результата: если задача убьёт
				// горутину через runtime.Goexit, обычный возврат из run не
				// случится и отправится именно она.
				res := Result[T]{Err: ErrGoexit}
				// Отправка — в defer, а не после вызова: defer выполняется
				// даже при runtime.Goexit, поэтому воркер в любом исходе
				// кладёт ровно один результат и fan-in-цикл ниже никогда не
				// зависает в ожидании недостающего. Благодаря буферу отправка
				// не блокирует. Порядок LIFO: сначала отправка, потом wg.Done.
				defer func() { out <- item{idx: i, res: res} }()
				res = run(ctx, fn)
			}()
		}

		// Fan-in перед yield: воркеры никогда не вызывают yield сами —
		// параллельные вызовы yield нарушили бы контракт итератора. Этот
		// единственный цикл — единственное место, где вызывается yield.
		// Ровно len(fns) итераций, потому что каждый воркер гарантированно
		// делает ровно одну отправку (см. defer выше).
		for range fns {
			it := <-out
			// yield возвращает false, когда потребитель вышел из цикла
			// (break/return). Тогда выходим и мы — а отложенные cancel и
			// wg.Wait аккуратно сворачивают оставшихся воркеров.
			if !yield(it.idx, it.res) {
				return
			}
		}
	}
}

// run выполняет одну задачу, превращая возможную панику в ошибку.
// Именованный результат res нужен, чтобы defer мог подменить возвращаемое
// значение уже после того, как паника случилась.
func run[T any](ctx context.Context, fn func(context.Context) (T, error)) (res Result[T]) {
	// Флаг «дошли до обычного возврата». Ключимся на нём, а не на значении
	// recover(): под GODEBUG=panicnil=1 recover() возвращает nil для
	// panic(nil), хотя паника была, — проверка `recover() != nil` в этом
	// режиме молча выдала бы панику за успех с нулевым значением.
	completed := false
	defer func() {
		if completed {
			return
		}
		// Сюда попадаем в двух случаях: паника внутри fn (recover её гасит и
		// отдаёт значение) или runtime.Goexit (recover возвращает nil, а
		// горутина всё равно умирает — тогда это присваивание никем не будет
		// прочитано, воркер отправит заготовленный ErrGoexit).
		res = Result[T]{Err: &PanicError{Value: recover(), Stack: debug.Stack()}}
	}()
	v, err := fn(ctx)
	completed = true
	return Result[T]{Value: v, Err: err}
}
