package settle

import (
	"context"
	"iter"
	"sync"
)

// Map применяет fn к каждому элементу последовательности in, выполняя не
// более n задач одновременно, и возвращает итератор по парам
// (индекс, Result) — тот же контракт, что у [Stream].
//
// Отличий от [Stream] ровно два, и оба про масштаб:
//
//   - Вход ленивый. in обходится по мере освобождения слотов, поэтому
//     миллион элементов не нужно материализовывать в срез, а горутин
//     одновременно живёт не больше n.
//   - Барьеров нет. Как только любая задача завершилась, освободившийся слот
//     тут же занимает следующий элемент входа. Это принципиально отличается
//     от обхода пачками (slices.Chunk + [AllSettled]), где вся пачка ждёт
//     самую медленную задачу в ней.
//
// Индекс — позиция элемента во входной последовательности: первый элемент
// получает 0, второй 1 и так далее. Результаты приходят в порядке завершения;
// чтобы получить их в порядке входа, оберните последовательность в [Ordered].
//
// Контракт совпадает с [Stream] дословно: ленивый запуск (задачи стартуют при
// обходе, каждый новый обход запускает всё заново), ровно один Result на
// элемент, паника внутри fn приезжает как *[PanicError], а runtime.Goexit —
// как [ErrGoexit], выход из цикла через break отменяет незавершённые задачи и
// дожидается их возврата.
//
// # Требование к входной последовательности
//
// Отмена в Go кооперативна, и это касается не только задач, но и входа. Пока
// in блокируется ВНУТРИ СЕБЯ, не отдавая очередной элемент, прервать её
// снаружи невозможно: у iter.Seq нет контекста, а Go не умеет прерывать
// чужой блокирующий вызов. Поэтому вход обязан либо завершаться сам, либо
// реагировать на отмену — иначе Map не сможет вернуться из обхода, ровно как
// не может вернуться, дожидаясь задачи, игнорирующей ctx.
//
// Для срезов, карт и любых конечных источников (slices.Values и подобные)
// требование выполняется само собой. Для источников, которые ждут данных —
// канал, курсор базы, очередь, — используйте [FromChannel] или напишите
// последовательность с select по ctx.Done() внутри. Контекст ей нужно
// передать тот же, что и в Map: производную отмену, которую Map делает на
// break, наружу он не отдаёт.
//
// Map паникует, если n <= 0: это ошибка вызывающего, а не состояние времени
// выполнения.
func Map[In, Out any](
	ctx context.Context,
	in iter.Seq[In],
	n int,
	fn func(context.Context, In) (Out, error),
) iter.Seq2[int, Result[Out]] {
	if n <= 0 {
		panic("settle: Map requires n > 0")
	}

	return func(yield func(int, Result[Out]) bool) {
		// Дочерний контекст: его отмена — рычаг, которым мы просим и
		// диспетчера, и работающие задачи свернуться, когда потребитель ушёл
		// раньше времени.
		ctx, cancel := context.WithCancel(ctx)

		type item struct {
			idx int
			res Result[Out]
		}
		// Буфер n: столько результатов может «созреть» одновременно, потому
		// что больше n задач в полёте не бывает. Дальше отправитель ждёт
		// потребителя — это и есть бэкпрешер: медленный потребитель
		// естественным образом тормозит чтение входа.
		out := make(chan item, n)

		// Отдельная wg только на диспетчера: он, в свою очередь, дожидается
		// всех задач. Порядок LIFO важен: сначала cancel (разбудить всех),
		// затем wg.Wait (проводить каждого до двери).
		var dispatcher sync.WaitGroup
		defer dispatcher.Wait()
		defer cancel()

		// sem — счётный семафор: занятый слот означает работающую задачу.
		// Слот берёт диспетчер перед запуском, освобождает сама задача.
		sem := make(chan struct{}, n)

		dispatcher.Add(1)
		go func() {
			defer dispatcher.Done()

			// tasks считает запущенные задачи. Add вызывается только здесь и
			// только до Wait ниже, поэтому гонки Add/Wait нет.
			var tasks sync.WaitGroup
			// close(out) — единственный сигнал «результатов больше не будет»:
			// длина входа заранее неизвестна, поэтому считать итерации, как
			// это делает Stream, нельзя.
			defer func() {
				tasks.Wait()
				close(out)
			}()

			idx := 0
			for v := range in {
				// Проверка до занятия слота, а не только после запуска:
				// select ниже при уже отменённом контексте мог бы выбрать
				// готовую ветку sem (выбор между готовыми ветвями случаен) и
				// запустить задачу после того, как потребитель ушёл.
				if ctx.Err() != nil {
					return
				}

				// Ждём свободный слот — либо отмены. Без второй ветви
				// диспетчер завис бы здесь навсегда, если потребитель ушёл,
				// а задачи ещё держат все слоты.
				select {
				case sem <- struct{}{}:
				case <-ctx.Done():
					return
				}

				i, v := idx, v
				idx++

				tasks.Add(1)
				go func() {
					defer tasks.Done()
					defer func() { <-sem }()

					// Пессимистичная заготовка: если задача убьёт горутину
					// через runtime.Goexit, обычного возврата из run не
					// случится и отправится именно она.
					res := Result[Out]{Err: ErrGoexit}
					defer func() {
						// В отличие от Stream, буфера «на всех» здесь нет:
						// длина входа неизвестна. Поэтому отправка может
						// заблокироваться, и её страхует ctx — иначе задача
						// повисла бы на отправке после ухода потребителя.
						// Результат при этом теряется, что контракту не
						// противоречит: после break результаты отбрасываются.
						select {
						case out <- item{idx: i, res: res}:
						case <-ctx.Done():
						}
					}()
					res = run(ctx, func(ctx context.Context) (Out, error) {
						return fn(ctx, v)
					})
				}()

				// Источник может оказаться бесконечным или блокирующим:
				// проверяем отмену и на этой стороне, чтобы выход из цикла
				// потребителя гарантированно останавливал и чтение входа.
				if ctx.Err() != nil {
					return
				}
			}
		}()

		// Fan-in перед yield: задачи никогда не вызывают yield сами —
		// параллельные вызовы нарушили бы контракт итератора. Этот цикл —
		// единственное место, где вызывается yield.
		for it := range out {
			if !yield(it.idx, it.res) {
				// Потребитель ушёл. Отложенные cancel и dispatcher.Wait
				// аккуратно сворачивают диспетчера и все живые задачи.
				return
			}
		}
	}
}

// FromChannel превращает канал в последовательность, пригодную для входа
// [Map]: чтение прекращается либо при закрытии канала, либо при отмене ctx.
//
// Голый канал таким входом быть не может. Последовательность вида
// «for v := range ch { yield(v) }» блокируется внутри себя, когда данных нет,
// и прервать её снаружи нельзя — [Map] будет ждать её сколько угодно. Здесь
// же ожидание идёт через select, поэтому отмена контекста разрывает и его.
//
// Передавайте тот же контекст, что и в [Map]: тогда общий дедлайн или отмена
// сворачивают конвейер целиком — и задачи, и чтение входа.
//
//	ctx, cancel := context.WithCancel(ctx)
//	defer cancel()
//
//	for i, r := range settle.Map(ctx, settle.FromChannel(ctx, jobs), 8, handle) {
//		// …
//	}
//
// Отменить чтение может и сам потребитель [Map]: выход из цикла через break
// возвращает в источник false, и FromChannel завершается на следующем же
// полученном элементе. Если канал при этом молчит, ждать придётся до отмены
// контекста — поэтому cancel и нужен.
func FromChannel[T any](ctx context.Context, ch <-chan T) iter.Seq[T] {
	return func(yield func(T) bool) {
		for {
			select {
			case v, ok := <-ch:
				if !ok || !yield(v) {
					return
				}
			case <-ctx.Done():
				return
			}
		}
	}
}
